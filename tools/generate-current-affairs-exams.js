#!/usr/bin/env node
/* Generate static /exam/date=YYYY-MM-DD/ pages for the published BS-date tests.
 * GitHub Pages cannot rewrite arbitrary paths to exam.html; run this after
 * changing Current-Affairs/tests.js so each new exam link works on refresh. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const base = path.join(root, 'Psc-preparation/Current-Affairs');
const template = fs.readFileSync(path.join(base, 'exam.html'), 'utf8');
const canonical = 'https://arunpanthi.com.np/Psc-preparation/Current-Affairs/exam.html';
const marker = '<!-- Generated by tools/generate-current-affairs-exams.js from exam.html. Do not edit directly. -->';
const check = process.argv.includes('--check');

if (process.argv.slice(2).some(arg => arg !== '--check')) {
  throw new Error('Usage: node tools/generate-current-affairs-exams.js [--check]');
}
if (!template.startsWith('<!DOCTYPE html>') || !template.includes('href="' + canonical + '"')) {
  throw new Error('Cannot find the doctype or canonical URL in the exam template');
}

const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(base, 'tests.js'), 'utf8'), context,
  { filename: 'tests.js', timeout: 1000 });
const dates = Object.keys(context.window.CA_TESTS || {}).sort();
const outputs = new Map();

function generated(html) {
  return html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + marker);
}

// Preserve older /exam/?date=... bookmarks in addition to /exam.html?date=....
outputs.set(path.join(base, 'exam/index.html'), generated(template));
for (const date of dates) {
  if (!/^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[0-2])$/.test(date)) {
    throw new Error('Invalid BS date key in tests.js: ' + date);
  }
  const datedCanonical = canonical.replace('exam.html', 'exam/date=' + date);
  outputs.set(path.join(base, 'exam', 'date=' + date, 'index.html'),
    generated(template.replace(canonical, datedCanonical)));
}

const stale = [];
for (const [file, html] of outputs) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== html) {
      stale.push(path.relative(root, file));
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== html) {
      fs.writeFileSync(file, html);
    }
  }
}
if (stale.length) {
  console.error('Missing or outdated exam pages (run this script without --check):\n' + stale.join('\n'));
  process.exitCode = 1;
} else {
  console.log((check ? 'Verified' : 'Generated') + ' ' + dates.length + ' dated exam page(s).');
}
