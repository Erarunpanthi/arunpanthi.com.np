#!/usr/bin/env python3
"""Generate and validate every legacy-URL redirect artefact from one source.

The site is served by GitHub Pages, so Apache rules never run in production;
404.html + js/legacy-redirects.js do the work. .htaccess still carries the same
rules for anyone hosting the repo on Apache.

This script rewrites, between the BEGIN/END markers:

  * the "Legacy / duplicate URL consolidation" block in .htaccess
  * js/legacy-redirects.js

and refuses to write anything if a redirect target is missing, noindex, or is
itself a redirect placeholder (a redirect chain, which Search Console reports
as "Page with redirect" and never passes ranking signals through).

Run: python3 tools/generate-redirects.py [--check]
"""
from __future__ import annotations

import os

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from redirects import (  # noqa: E402
    DUPLICATES, HANDWRITTEN_REDIRECTS, MOVED_FILES, NEC_NOTES_PLACEHOLDERS,
    PAST_QUESTION_SUBJECTS,
    PAST_QUESTIONS_HUB, PLACEHOLDERS, PSC_SYLLABUS_PLACEHOLDERS,
)

ROOT = Path(__file__).resolve().parents[1]

# These scripts are run from the repo root, but be explicit so a stray cwd can
# never write the wrong sitemap or redirect map.
os.chdir(ROOT)
BASE = "https://arunpanthi.com.np"
BEGIN = "# BEGIN legacy-redirects (generated by tools/generate-redirects.py)"
END = "# END legacy-redirects"


def route_file(route: str) -> Path | None:
    """Map a public route to the file that serves it."""
    clean = route.strip("/")
    if not clean:
        return ROOT / "index.html"
    direct = ROOT / clean
    if direct.is_dir():
        return direct / "index.html"
    for candidate in (ROOT / (clean + ".html"), direct):
        if candidate.is_file():
            return candidate
    return None


def validate() -> list[str]:
    problems: list[str] = []
    targets = (
        {t for t, _, _ in PLACEHOLDERS.values()}
        | set(DUPLICATES.values())
        | set(MOVED_FILES.values())
    )
    for target in sorted(targets):
        if target.startswith(BASE):
            continue
        path = route_file(target)
        if path is None:
            problems.append(f"missing target page: {target}")
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "noindex" in text.lower():
            problems.append(f"target is noindex: {target}")
        if "http-equiv=\"refresh\"" in text.lower():
            problems.append(f"target is itself a redirect placeholder: {target}")
    return problems


def htaccess_block() -> str:
    subjects = "|".join(PAST_QUESTION_SUBJECTS)
    notes = "|".join(NEC_NOTES_PLACEHOLDERS)
    bodies = "|".join(
        b for b in PSC_SYLLABUS_PLACEHOLDERS
    )
    return "\n".join([
        BEGIN,
        "# Same map as js/legacy-redirects.js, for Apache hosts. Regenerate with",
        "# python3 tools/generate-redirects.py",
        "",
        "# Duplicates of pages that already have a canonical URL.",
        "RewriteRule ^Home\\.html$ / [R=301,L,NC]",
        "RewriteRule ^Home/?$ / [R=301,L,NC]",
        "RewriteRule ^Home/Notes/?$ /NEC-license-preparation/Notes [R=301,L,NC]",
        "RewriteRule ^Home/Solutions/?$ /Resources/Solutions [R=301,L,NC]",
        "RewriteRule ^Home/past-questions/?$ /Resources/Past-Questions [R=301,L,NC]",
        "RewriteRule ^Resources/Past-Questions/Past-Questions(/.*)?$ /Resources/Past-Questions [R=301,L,NC]",
        "RewriteRule ^NEC-license-preparation/Notes/NEC-license-preparation(/.*)?$ /NEC-license-preparation/Notes/ [R=301,L,NC]",
        "",
        "# Notes that were published as an extension-less .html file.",
        "RewriteRule ^NEC-license-preparation/Notes/Engineering-Drawing(\\.html)?/?$ /NEC-license-preparation/Notes/Engineering-Drawing/ [R=301,L,NC]",
        "RewriteRule ^NEC-license-preparation/Notes/Construction-Materials(\\.html)?/?$ /NEC-license-preparation/Notes/Construction-Materials/ [R=301,L,NC]",
        "",
        "# Thin placeholder pages, consolidated onto the page that covers the topic.",
        f"RewriteRule ^Resources/Past-Questions/({subjects})/?$ {PAST_QUESTIONS_HUB} [R=301,L,NC]",
        f"RewriteRule ^NEC-license-preparation/Notes/({notes})/?$ /NEC-license-preparation/Notes/ [R=301,L,NC]",
        f"RewriteRule ^Psc-preparation/Syllabus/({bodies})/?$ /Psc-preparation/Syllabus/ [R=301,L,NC]",
        "RewriteRule ^Psc-preparation/Syllabus/nepal-telecom-syllabus/?$ /Psc-preparation/Syllabus/Nepal-telecom [R=301,L,NC]",
        "RewriteRule ^NEC-license-preparation/MCQ/?$ /NEC-license-preparation/Test/ [R=301,L,NC]",
        "RewriteRule ^NEC-license-preparation/exam-preparation/?$ /NEC-license-preparation/ [R=301,L,NC]",
        "RewriteRule ^Psc-preparation/Psc-video/?$ /Psc-video/ [R=301,L,NC]",
        END,
    ]) + "\n"


def js_file() -> str:
    routes: dict[str, str] = dict(DUPLICATES)
    routes.update(MOVED_FILES)
    routes.update(HANDWRITTEN_REDIRECTS)
    for source, (target, _, _) in PLACEHOLDERS.items():
        routes[source] = target
    payload = json.dumps(dict(sorted(routes.items())), indent=2)
    return f"""// GENERATED FILE — edit tools/redirects.py and run
// `python3 tools/generate-redirects.py` instead of changing this by hand.
//
// GitHub Pages answers 404 for every retired URL, so 404.html loads this file to
// forward the visitor (and Googlebot) to the page that replaced it. The same map
// is written into .htaccess for Apache hosts.
(function () {{
  "use strict";

  var ROUTES = {payload.replace(chr(10), chr(10) + "  ")};

  var PAST_QUESTION_SUBJECTS = {json.dumps(PAST_QUESTION_SUBJECTS)};

  var path = window.location.pathname.replace(/\\/index\\.html$/i, "");
  path = path.replace(/\\/+$/, "");
  if (path === "") path = "/";

  var target = ROUTES[path] || ROUTES[path + "/"];

  if (!target) {{
    // Any leftover subject route under the collection hub (including the old
    // duplicated /Resources/Past-Questions/Past-Questions/ folder).
    var match = path.match(/^\\/Resources\\/Past-Questions\\/(?:Past-Questions\\/)?([^/]+)$/);
    if (match && PAST_QUESTION_SUBJECTS.indexOf(match[1]) !== -1) {{
      target = "{PAST_QUESTIONS_HUB}";
    }}
  }}

  if (target && target !== path) {{
    window.location.replace(target + (window.location.search || "") + (window.location.hash || ""));
  }}
}})();
"""


def write(path: Path, content: str, check: bool, problems: list[str]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return
    problems.append(f"{path.relative_to(ROOT)} is out of date")
    if not check:
        path.write_text(content, encoding="utf-8")


def main(check: bool) -> int:
    problems = validate()

    htaccess_path = ROOT / ".htaccess"
    htaccess = htaccess_path.read_text(encoding="utf-8")
    if BEGIN in htaccess and END in htaccess:
        updated = re.sub(
            re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?",
            htaccess_block(),
            htaccess,
            flags=re.S,
        )
        write(htaccess_path, updated, check, problems)
    else:
        problems.append(".htaccess is missing the legacy-redirects markers")

    write(ROOT / "js" / "legacy-redirects.js", js_file(), check, problems)

    for problem in problems:
        print("FAIL", problem)
    if not problems:
        print("Redirect map is consistent")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main("--check" in sys.argv))
